/**
 * Wrapped CLI shims for external subagents.
 *
 * With `captureScope: pid` (default), the wrapped process and its same-process
 * child sessions are captured, but a harness that spawns a DIFFERENT CLI
 * (codex/claude/...) for a subagent would escape capture. The deterministic fix
 * is to point the harness's subagent CLI at a shim that invokes `looper <cli>`.
 * Each shim run gets its own bridge + control plane, so visibility is shared,
 * not lost — this is augmentation, not the recursive-CLI anti-pattern.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

export interface ShimPlan {
  /** CLI name the harness is configured to spawn (e.g. "codex"). */
  cli: string;
  /** Directory to install the shim into. */
  dir: string;
  /** Path to looper entry (default ~/.local/bin/looper). */
  looperBin?: string;
}

export function shimScript(cli: string, looperBin = "~/.local/bin/looper"): string {
  const expanded = looperBin.startsWith("~") ? path.join(os.homedir(), looperBin.slice(2)) : looperBin;
  return `#!/usr/bin/env bun\n// Generated by looper — wraps ${cli} so its traffic is captured.\nexec ${JSON.stringify(expanded)} ${JSON.stringify(cli)} "$@"\n`;
}

export function shimPath(plan: ShimPlan): string {
  return path.join(plan.dir, plan.cli);
}

/** Install a shim. Idempotent. Returns the path and whether it changed. */
export function installShim(plan: ShimPlan): { path: string; changed: boolean } {
  fs.mkdirSync(plan.dir, { recursive: true });
  const file = shimPath(plan);
  const content = shimScript(plan.cli, plan.looperBin);
  const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (existing === content) return { path: file, changed: false };
  fs.writeFileSync(file, content, { mode: 0o755 });
  return { path: file, changed: true };
}

/** The exact config line a harness/operator must set to use the shim. */
export function shimConfigHint(plan: ShimPlan): string {
  return `Set the harness subagent CLI for ${plan.cli} to ${shimPath(plan)} (or prepend ${plan.dir} to PATH).`;
}
